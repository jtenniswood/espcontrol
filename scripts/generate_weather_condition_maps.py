#!/usr/bin/env python3
"""Generate bounded weather lookup tables from the existing production helpers."""
import argparse
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def rendered():
 source=(ROOT/'components/espcontrol/button_grid_weather_forecast.h').read_text()
 normalize=source.split('inline std::string normalize_weather_state',1)[1].split('inline const char* weather_icon_for_state',1)[0]
 aliases=[]
 for condition,result in re.findall(r'if\s*\((.*?)\)\s*return "([^"]+)";',normalize,re.S):
  aliases += [(value,result) for value in re.findall(r'normalized == "([^"]+)"',condition)]
 icons={}
 icon_source=source.split('inline const char* weather_icon_for_state',1)[1].split('inline bool weather_state_has_localized_label',1)[0]
 for condition,icon in re.findall(r'if\s*\((.*?)\)\s*return find_icon\("([^"]+)"\);',icon_source,re.S):
  for value in re.findall(r'normalized == "([^"]+)"',condition):icons[value]=icon
 label_source=source.split('inline std::string weather_label_for_state',1)[1].split('#include "button_grid_weather_daily_data.h"',1)[0]
 labels={}
 for condition,label in re.findall(r'if\s*\((.*?)\)\s*return espcontrol_i18n\(std::string\("([^"]+)"\)\);',label_source,re.S):
  for value in re.findall(r'normalized == "([^"]+)"',condition):labels[value]=label
 assert len(aliases)>=40 and len(icons)>=29 and len(labels)>=29,(len(aliases),len(icons),len(labels))
 names=list(icons)
 for name in labels:
  if name not in names and name not in ('unknown',''):names.append(name)
 names=[name for name in names if name]
 lines=['#pragma once','// Generated by scripts/generate_weather_condition_maps.py. Do not edit.', '#include <string_view>', 'namespace espcontrol::weather {', 'struct ConditionAlias {std::string_view from,to;};','inline constexpr ConditionAlias CONDITION_ALIASES[]={']
 lines += ['  {"'+a+'","'+b+'"},' for a,b in aliases]
 lines += ['};','struct ConditionRow {std::string_view state;const char *icon,*label;};','inline constexpr ConditionRow CONDITION_ROWS[]={']
 lines += ['  {"'+name+'","'+icons.get(name,'Weather Cloudy Alert')+'","'+labels.get(name,'Unavailable')+'"},' for name in names]
 lines += ['};','inline constexpr size_t CONDITION_COUNT=sizeof(CONDITION_ROWS)/sizeof(CONDITION_ROWS[0]);','static_assert(CONDITION_COUNT<=256,"Weather index must fit one byte");','}  // namespace espcontrol::weather','']
 return '\n'.join(lines)
def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args();target=ROOT/'components/espcontrol/weather_condition_maps_generated.h';text=rendered()
 if args.check:
  if not target.exists() or target.read_text()!=text:raise SystemExit('Weather condition maps are stale; regenerate them.')
 else:target.write_text(text)
if __name__=='__main__':main()
